"""
Langchain - Runtime and Tools
"""

from dotenv import load_dotenv
from dataclasses import dataclass
from langchain.tools import tool , ToolRuntime
from langchain.agents import create_agent

load_dotenv(override=True)

@dataclass
class Context:
    user_id : str
    db_session : str


@tool
def fetch_user_balance(currency:str, runtime:ToolRuntime[Context])->str:
    """ fetch users account balance for a specific currency   """

    user_id = runtime.context.user_id
    db_session = runtime.context.db_session

    print(f"[System log]: Using {db_session} to query account for User ID: {user_id}")
    
    return f"User {user_id} has a balance of 1500 {currency}."



# agent
agent = create_agent(
    model = "gpt-5.4-mini",
    tools = [fetch_user_balance],
    context_schema = Context
)

# run code
if __name__ == "__main__":
    response = agent.invoke({"messages": [{"role":"user", "content": "what is my USD balance?"}]},
    context = Context(user_id="001", db_session="12356")

    )

    print("---- RESULT -----")
    print(response["messages"][-1].content)


"""
currency is generated by the LLM

ToolRuntime is a class which takes in the argument as Context another class defined under the decorator @tool.
ToolRuntime has runtime.store, runtime.config, runtime.state, runtime.context

'runtime.context' is an instance of the class 'Context' passed as arg to the ToolRuntime.



"""